def find_paragraph(doc: Document, exact_text: str):
    for paragraph in doc.paragraphs:
        if paragraph.text.strip() == exact_text:
            return paragraph
    raise RuntimeError(f"Could not find paragraph: {exact_text}")


def insert_paragraph_before(doc: Document, ref_para, text: str = "", style: str | None = None):
    paragraph = doc.add_paragraph(text, style=style)
    ref_para._p.addprevious(paragraph._p)
    return paragraph


def delete_paragraph(paragraph) -> None:
    element = paragraph._element
    element.getparent().remove(element)
    paragraph._p = paragraph._element = None


def replace_section_body(doc: Document, heading_text: str, next_heading_text: str, paragraphs: list[str]) -> None:
    heading = find_paragraph(doc, heading_text)
    next_heading = find_paragraph(doc, next_heading_text)
    in_range = False
    to_delete = []
    for paragraph in doc.paragraphs:
        if paragraph._p is heading._p:
            in_range = True
            continue
        if paragraph._p is next_heading._p:
            break
        if in_range:
            to_delete.append(paragraph)
    for paragraph in to_delete:
        delete_paragraph(paragraph)
    for text in paragraphs:
        insert_paragraph_before(doc, next_heading, text)


def insert_paragraphs_after(doc: Document, anchor_text: str, paragraphs: list[str]) -> None:
    anchor = find_paragraph(doc, anchor_text)
    for text in reversed(paragraphs):
        paragraph = doc.add_paragraph(text)
        anchor._p.addnext(paragraph._p)


def insert_picture_before(doc: Document, ref_para, image_path: Path, width_inches: float):
    paragraph = doc.add_paragraph()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    paragraph.paragraph_format.keep_with_next = True
    paragraph.paragraph_format.keep_together = True
    paragraph.add_run().add_picture(str(image_path), width=Inches(width_inches))
    ref_para._p.addprevious(paragraph._p)
    return paragraph


def replace_exact_paragraph(doc: Document, old: str, new: str) -> None:
    paragraph = find_paragraph(doc, old)
    paragraph.text = new


def rename_heading(doc: Document, old: str, new: str) -> None:
    find_paragraph(doc, old).text = new


