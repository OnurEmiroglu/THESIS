def export_pdf_with_word() -> None:
    tmp_pdf = PDF.with_name(PDF.stem + "_export_tmp.pdf")
    if tmp_pdf.exists():
        tmp_pdf.unlink()
    ps = (
        "$ErrorActionPreference = 'Stop'; "
        f"$tmp = '{str(tmp_pdf)}'; "
        "if (Test-Path -LiteralPath $tmp) { Remove-Item -LiteralPath $tmp -Force }; "
        "$word = New-Object -ComObject Word.Application; "
        "$word.Visible = $false; "
        "try { "
        f"$doc = $word.Documents.Open('{str(DST)}', $false, $true); "
        "$doc.ExportAsFixedFormat($tmp, 17); "
        "$doc.Close($false); "
        "} finally { $word.Quit() }; "
        f"Move-Item -LiteralPath $tmp -Destination '{str(PDF)}' -Force"
    )
    subprocess.run(
        ["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-Command", ps],
        cwd=str(ROOT),
        check=True,
        capture_output=True,
        text=True,
    )


def export_pdf_with_libreoffice() -> None:
    soffice = shutil.which("soffice")
    if not soffice:
        raise RuntimeError("LibreOffice soffice not found on PATH")
    subprocess.run(
        [
            soffice,
            "--headless",
            "--convert-to",
            "pdf",
            "--outdir",
            str(PDF.parent),
            str(DST),
        ],
        cwd=str(ROOT),
        check=True,
        capture_output=True,
        text=True,
    )


def export_pdf() -> bool:
    try:
        export_pdf_with_libreoffice()
        return True
    except Exception as lo_err:
        print(f"LibreOffice PDF export unavailable or failed: {lo_err}")

    if sys.platform.startswith("win"):
        try:
            export_pdf_with_word()
            return True
        except Exception as word_err:
            print(f"Microsoft Word PDF export failed: {word_err}")
    return False


def main() -> int:
    if not SRC.exists():
        raise FileNotFoundError(SRC)
    if not PIPELINE_FIGURE.exists():
        raise FileNotFoundError(
            f"{PIPELINE_FIGURE} does not exist. Run scripts/figures/gen_pipeline_architecture_figure.py first."
        )

    shutil.copy2(SRC, DST)
    doc = Document(DST)
    replace_visible_version_refs(doc)
    update_front_page_references(doc)
    replace_section_body(doc, "1.3 Background and Related Work", "1.4 Contributions", LIT_REVIEW_PARAS)
    apply_markov_matrix(doc)
    apply_formula_explanations(doc)
    apply_ppo_rationale(doc)
